// Packs the prerendered site (./build) into worker/files.generated.js so the
// site Worker serves every page from its own bundle. This keeps deploys to a
// single script upload (no separate asset-upload session) and works the same
// from a laptop, GitHub Actions or Workers Builds.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { extname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { OG_PAGES, ogFile } from '../src/lib/og.ts';

const root = fileURLToPath(new URL('..', import.meta.url));
const build = join(root, 'build');
const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.webmanifest': 'application/manifest+json; charset=utf-8',
  '.xml': 'application/xml; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.webp': 'image/webp',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
};
const TEXT = new Set(['.html', '.css', '.js', '.json', '.webmanifest', '.xml', '.txt', '.svg']);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

// Every page listed in src/lib/og.ts must have its OG card, or its og:image would 404.
const missingOg = OG_PAGES.map((p) => ogFile(p.path)).filter((f) => !statSync(join(build, 'og', f), { throwIfNoEntry: false }));
if (missingOg.length) {
  throw new Error(`Missing OG images: ${missingOg.join(', ')}. Run: pnpm --filter @searchkeep/site run render:assets`);
}

const files = {};
let bytes = 0;
for (const file of walk(build).sort()) {
  const ext = extname(file).toLowerCase();
  const type = TYPES[ext];
  if (!type) throw new Error(`No content type for ${file}`);
  const buf = readFileSync(file);
  bytes += buf.length;
  const path = '/' + relative(build, file).split(sep).join('/');
  const etag = `"${createHash('sha256').update(buf).digest('base64url').slice(0, 22)}"`;
  files[path] = TEXT.has(ext) ? { type, etag, text: buf.toString('utf8') } : { type, etag, b64: buf.toString('base64') };
}
writeFileSync(
  join(root, 'worker/files.generated.js'),
  `// Generated by scripts/embed-build.mjs — do not edit.\nexport const FILES = ${JSON.stringify(files)};\n`,
);
console.log(`Embedded ${Object.keys(files).length} files (${(bytes / 1024).toFixed(0)} KiB) into worker/files.generated.js`);
