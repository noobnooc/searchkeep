// Embeds migrations/*.sql into src/migrations.generated.ts so the Worker can
// apply pending migrations itself (Workers Builds' default token cannot run
// `wrangler d1 migrations apply`). Run via `pnpm run db:generate`.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'migrations');
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const body = files
  .map((name) => `  { name: ${JSON.stringify(name)}, sql: ${JSON.stringify(readFileSync(join(dir, name), 'utf8'))} },`)
  .join('\n');
export const output = `// Generated by scripts/embed-migrations.mjs — do not edit.\nexport const MIGRATIONS: ReadonlyArray<{ name: string; sql: string }> = [\n${body}\n];\n`;
if (process.argv.includes('--check')) {
  const current = readFileSync(join(root, 'src/migrations.generated.ts'), 'utf8');
  if (current !== output) {
    console.error('src/migrations.generated.ts is stale. Run: pnpm --filter @searchkeep/store-d1 run db:generate');
    process.exit(1);
  }
} else {
  writeFileSync(join(root, 'src/migrations.generated.ts'), output);
  console.log(`Embedded ${files.length} migration(s).`);
}
